"""Register a built release APK in output/releases.json and output/RELEASES.md.

Run this after every release build that is meant to be kept (dev builds are rejected):

    python tools/register_release.py output/FWT-Reborn-Patched-2.5.39-release.apk \
        --features option_max_attributes,rune_option_quality \
        --notes "..."

It appends one entry with the sha256, size, patched version, feature list and notes, then
regenerates the markdown table so ``output/RELEASES.md`` always shows the incremental
history in build order.
"""

from __future__ import annotations

import argparse
import contextlib
import datetime as dt
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from core.core_patches import is_dev_output_path  # noqa: E402
from core.patch_inspector import inspect_apk, verify_release_report  # noqa: E402

OUTPUT = ROOT / "output"
REGISTRY = OUTPUT / "releases.json"
TABLE = OUTPUT / "RELEASES.md"


def validate_release_apk(apk: Path, *, kind: str = "release") -> None:
    """Refuse development builds and APKs that fail release verification."""
    if kind != "release" or is_dev_output_path(apk):
        raise ValueError("Development builds (--dev) cannot be registered as releases")
    report = inspect_apk(apk)
    if report.build_identity == "dev":
        raise ValueError(
            "Development builds (--dev) cannot be registered as releases (identity is dev)"
        )
    problems = verify_release_report(report)
    if problems:
        raise ValueError("APK failed release verification: " + "; ".join(problems))


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_registry() -> list[dict[str, Any]]:
    if REGISTRY.exists():
        with REGISTRY.open(encoding="utf-8") as handle:
            data = json.load(handle)
            if isinstance(data, dict):
                releases: list[dict[str, Any]] = data.get("releases", [])
                return releases
            entries: list[dict[str, Any]] = data
            return entries
    return []


def render(entries: list[dict[str, Any]]) -> str:
    lines = [
        "# Releases",
        "",
        "Incremental history of APKs generated in `output/`. One entry per build worth",
        "keeping, in the order they were built. Regenerated by",
        "`tools/register_release.py`.",
        "",
        "| # | date | version | kind | features | sha256 | bytes | file |",
        "| - | ---- | ------- | ---- | -------- | ------ | ----- | ---- |",
    ]
    def _md_cell(value: str) -> str:
        return value.replace("|", "\\|").replace("\r", " ").replace("\n", " ")

    for i, entry in enumerate(entries, 1):
        features = _md_cell(", ".join(entry.get("features") or []) or "-")
        version = _md_cell(str(entry["version"]))
        lines.append(
            f"| {i} | {entry['date']} | {version} | {entry['kind']} | {features} "
            f"| `{entry['sha256'][:16]}` | {entry['bytes']} | `{entry['file']}` |"
        )
    lines.append("")
    for i, entry in enumerate(entries, 1):
        if entry.get("notes"):
            lines.append(f"- **#{i} {entry['version']}** ({entry['kind']}): {entry['notes']}")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    with contextlib.suppress(ImportError):
        from dotenv import load_dotenv

        load_dotenv(ROOT / ".env", override=False)

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("apk")
    parser.add_argument("--features", default="", help="comma-separated feature list")
    parser.add_argument("--notes", default="")
    parser.add_argument("--kind", default="release", choices=("release",))
    parser.add_argument("--version", default="")
    args = parser.parse_args()

    apk = Path(args.apk).expanduser()
    if not apk.is_absolute() and not apk.exists():
        apk = ROOT / apk
    if not apk.exists():
        raise SystemExit(f"APK not found: {apk}")

    try:
        validate_release_apk(apk, kind=args.kind)
    except ValueError as exc:
        raise SystemExit(str(exc)) from exc

    entries = load_registry()
    digest = sha256_of(apk)
    if any(entry["sha256"] == digest for entry in entries):
        print(f"already registered (sha256 {digest[:16]})")
        return

    features = [f.strip() for f in args.features.split(",") if f.strip()]
    entry = {
        "date": dt.datetime.now().strftime("%Y-%m-%d %H:%M"),
        "version": args.version or apk.stem,
        "kind": args.kind,
        "file": apk.name,
        "bytes": apk.stat().st_size,
        "sha256": digest,
        "features": features,
        "notes": args.notes,
    }
    entries.append(entry)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    reg_tmp = REGISTRY.with_name(REGISTRY.name + ".tmp")
    tbl_tmp = TABLE.with_name(TABLE.name + ".tmp")
    reg_tmp.write_text(json.dumps({"releases": entries}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    reg_tmp.replace(REGISTRY)
    tbl_tmp.write_text(render(entries), encoding="utf-8")
    tbl_tmp.replace(TABLE)
    print(f"registered: {entry['version']} ({entry['kind']}) sha256={digest[:16]}")


if __name__ == "__main__":
    main()
